package seng202.team1.auth;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import javax.crypto.Mac;
import javax.crypto.spec.SecretKeySpec;
import java.nio.charset.StandardCharsets;
import java.time.Instant;
import java.util.Base64;
import java.util.HexFormat;

@Service
public class TokenService {

    private String secret = "";

    private final int EXPIRY_DAYS = 30;
    private final int EXPIREY_SEC = EXPIRY_DAYS * 24 * 60 * 60;

    // kc token form: <id>::<expires>::<s_hash>

    public TokenService(@Value("${app.token-secret}") String secret) {
        this.secret = secret;
    }

    public String signToken(long userId) {

        // Build the token contents
        long expires = Instant.now().getEpochSecond() + EXPIREY_SEC;
        String payload = userId + "::" + expires;

        // Hash the token to prove it's valid by tas
        String signature = sign(payload);
        String token = payload + "::" + signature;

        return token;
    }


    private String sign(String payload) {
        try {

            // Setup the hasher
            Mac mac = Mac.getInstance("HmacSHA256");
            mac.init(new SecretKeySpec(secret.getBytes(), "HmacSHA256"));

            // Hash the payload
            byte[] hash = mac.doFinal(payload.getBytes());
            return HexFormat.of().formatHex(hash);

        } catch (Exception e) {
            throw new IllegalStateException("HMAC failure", e);
        }
    }

    public Long parseToken(String token) {

        try{

            // Token must be of form id::expires::signed
            String[] parts = token.split("::", 3);
            if (parts.length != 3)
                return -1L;

            // Parse the token
            long userId = Long.parseLong(parts[0]);
            long expires = Long.parseLong(parts[1]);
            String signature = parts[2];

            // Token expired
            if (Instant.now().getEpochSecond() > expires)
                return -1L;

            // Token not generated by tas
            String expected = sign(userId + "::" + expires);
            if (!expected.equals(signature))
                return -1L;

            // Must be a valid token
            return userId;

        } catch (Exception e) {

            // Anything fails must be a bad token
            return -1L;

        }
    }
}